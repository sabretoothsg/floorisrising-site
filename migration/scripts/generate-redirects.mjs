#!/usr/bin/env node
// Generate public/_redirects (Cloudflare Pages format) for legacy URL preservation.
//
// Episode URLs (/podcast/<slug>/) are unchanged, so they don't need redirects.
// The old WordPress site exposed:
//   - blog posts at /<slug>/   → new /blog/<slug>/
//   - /episode/                → static landing, redirect to /podcast/
//   - the captivate feed paths → /feed/podcast.xml

import { readdir, writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..", "..");
const POSTS_DIR = join(REPO_ROOT, "src", "content", "posts");
const PAGES_DIR = join(REPO_ROOT, "src", "pages");
const OUT = join(REPO_ROOT, "public", "_redirects");

// Slugs that ARE used by real Astro pages must NOT be claimed as blog
// post redirects. Blog post redirect line = `/<slug>/  /blog/<slug>/  301`
// — Cloudflare evaluates static files first, then redirects. To be safe
// we still skip any slug matching a real page.
const RESERVED_TOP_LEVEL = new Set([
  "", "podcast", "blog", "feed", "about", "listen", "contact",
  "privacy", "terms", "episode",
]);

async function postSlugs() {
  const entries = await readdir(POSTS_DIR);
  return entries.filter((f) => f.endsWith(".md")).map((f) => f.replace(/\.md$/, ""));
}

async function main() {
  const slugs = await postSlugs();
  const skipped = [];
  const lines = [
    "# Generated by migration/scripts/generate-redirects.mjs",
    "# Legacy WordPress URLs → new Astro paths.",
    "",
    "# Old single-page episode template path → episode index.",
    "/episode/    /podcast/    301",
    "/episode     /podcast/    301",
    "",
    "# Legacy Captivate-style feed paths → new podcast RSS.",
    "/feed         /feed/podcast.xml  301",
    "/feed/        /feed/podcast.xml  301",
    "/podcast/feed /feed/podcast.xml  301",
    "",
    "# Legacy blog post URLs (/<slug>/) → /blog/<slug>/.",
  ];
  for (const slug of slugs) {
    if (RESERVED_TOP_LEVEL.has(slug)) {
      skipped.push(slug);
      continue;
    }
    lines.push(`/${slug}/    /blog/${slug}/    301`);
    lines.push(`/${slug}     /blog/${slug}/    301`);
  }
  lines.push("");
  await writeFile(OUT, lines.join("\n"));
  console.log(`Wrote ${OUT} with ${slugs.length - skipped.length} blog redirects.`);
  if (skipped.length) {
    console.log(`Skipped (collide with reserved top-level paths): ${skipped.join(", ")}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
